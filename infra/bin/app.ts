#!/usr/bin/env node
// =====================================================================================
// 【デモ1】別のチームも、同じ部品を使う（ダッシュボードの app.ts と並べて見る）
//
// 今の困りごと
//   ・チームごとに作り方がばらばらだと、サービスが増えるたびにインフラ担当の確認が増える。
//
// ここで見ていただくこと
//   ・POS 連携のチームも、同じ ApiService を使う。ダッシュボードとの違いは2点だけ。
//       画面がない（site を書いていない）／このサービス専用のDBを作る（db: 'new'）
//   ・専用のDBは、部品が暗号化して作る（INF-12）。このファイルに暗号化の設定はない。
//   ・CPU・メモリ・タスク数は、環境ごとの既定値が入る。必要な項目だけ上書きできる（下の本番環境）。
//     上書きしても、検査のルール（検証・本番は2タスク以上など）はそのままかかる。
//
// これで解決すること
//   ・4つ目以降のサービスも同じ部品で用意でき、インフラ担当の作業は増えない（新サービス 15人日 → 約2人日）。
// =====================================================================================
//
// =====================================================================================
// 【デモ3】部品の新しい版を取り込む時期は、各チームが選べる
//
// 今の困りごと
//   ・共通の部分を一斉に更新すると、リリース直前のチームまで作業が止まる。
//
// ここで見ていただくこと
//   ・infra/package.json の @acme/platform は 1.0.0 のまま。
//     ダッシュボードが 1.1.0（ログの保管1年）を取り込んでも、このチームは前の版のまま動き続ける。
//
// これで解決すること
//   ・各チームは自分の都合のよい時期に、PR で新しい版を取り込める。部品の更新で開発は止まらない。
// =====================================================================================
import { ApiService, PlatformStage } from '@acme/platform';
import { App, aws_ecs as ecs } from 'aws-cdk-lib';

/**
 * POS 連携 API（デモでは synth のみ。デプロイしない）
 * 店舗の POS からは本来 VPN 経由で接続する想定（デモの範囲外）。
 */
const app = new App();
const image = ecs.ContainerImage.fromRegistry('public.ecr.aws/nginx/nginx:stable'); // アプリ本体は仮

// ── 開発環境 ─────────────────────────────────────────────────────────────────
// ダッシュボードの開発環境と並べて見る
const dev = new PlatformStage(app, 'Dev', { envType: 'dev' });
new ApiService(dev, 'PosApi', {
  service: 'pos',
  image,
  db: 'new', //   ダッシュボードとの違い①：このサービス専用のDBを作る（暗号化は部品が入れる）
}); //            ダッシュボードとの違い②：site がない ＝ 画面なし。入口はすべてを API へ流す

// ── 検証環境 ─────────────────────────────────────────────────────────────────
// 何も書かなければ、検証環境の既定値（0.25 vCPU・512MiB・2タスク・Multi-AZ）
const stg = new PlatformStage(app, 'Stg', { envType: 'stg' });
new ApiService(stg, 'PosApi', {
  service: 'pos',
  image,
  db: 'new',
});

// ── 本番環境 ─────────────────────────────────────────────────────────────────
// 既定値（0.5 vCPU・1GiB・2〜4タスク）から、このサービスに必要な項目だけ上書きする
// POS は全店の締めの時間に負荷が集中するので、本番だけ大きくしている
const prod = new PlatformStage(app, 'Prod', { envType: 'prod' });
new ApiService(prod, 'PosApi', {
  service: 'pos',
  image,
  db: 'new',
  cpu: 1024, //      1 vCPU（締めの時間の集計に合わせて）
  memoryMiB: 2048, // 2 GiB
  minTasks: 3, //    いつも3タスク。1つ落ちても余裕を残す
  maxTasks: 12, //   締めの時間は12タスクまで増やす
});
